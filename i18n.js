    // labels
    const authLabels = document.querySelectorAll('.auth-form .form-group label');
    if (authLabels[0]) authLabels[0].textContent = dict['اسم المستخدم'];
    if (authLabels[1]) authLabels[1].textContent = dict['كلمة السر'];
