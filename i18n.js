    const cfpLabels = document.querySelectorAll('.cfp-body .form-group label');
    if (cfpLabels[0]) cfpLabels[0].textContent = dict['label-name'];
    if (cfpLabels[1]) cfpLabels[1].textContent = dict['label-email'];
    if (cfpLabels[2]) cfpLabels[2].textContent = dict['label-subject'];
    if (cfpLabels[3]) cfpLabels[3].textContent = dict['label-message'];
