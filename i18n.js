/* ─────────────────────────────────
   Get / Set / Toggle language
───────────────────────────────── */
function getLang() {
  return localStorage.getItem('lang') || 'ar';
}

function setLang(lang) {
  localStorage.setItem('lang', lang);
  applyLang(lang);
}

function toggleLang() {
  const current = getLang();
  setLang(current === 'ar' ? 'en' : 'ar');
}

/* ─────────────────────────────────
   Core apply function
───────────────────────────────── */
function applyLang(lang) {
  const dict  = TRANSLATIONS[lang]  || TRANSLATIONS['ar'];
  const pdict = PAGE_CONTENT[lang]  || PAGE_CONTENT['ar'];
  const isAr  = lang === 'ar';

  /* 1. html dir + lang */
  document.documentElement.lang = lang;
  document.documentElement.dir  = isAr ? 'rtl' : 'ltr';

  /* 2. data-i18n → textContent */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = dict[key] || pdict[key];
    if (val !== undefined) el.textContent = val;
  });

  /* 3. data-i18n-html → innerHTML */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    const val = pdict[key] || dict[key];
    if (val !== undefined) el.innerHTML = val;
  });

  /* 4. data-i18n-placeholder → placeholder */
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = dict[key] || pdict[key];
    if (val !== undefined) el.placeholder = val;
  });

  /* 5. data-i18n-value → value (for buttons/inputs) */
  document.querySelectorAll('[data-i18n-value]').forEach(el => {
    const key = el.getAttribute('data-i18n-value');
    const val = dict[key] || pdict[key];
    if (val !== undefined) el.value = val;
  });

  /* 6. Lang toggle button label */
  document.querySelectorAll('.lang-toggle-text').forEach(el => {
    el.textContent = isAr ? 'English' : 'عربي';
  });

  /* 7. Theme toggle text */
  const isLight = document.body.classList.contains('light-mode');
  document.querySelectorAll('.theme-toggle-text').forEach(el => {
    el.textContent = isLight
      ? (dict['الوضع الليلي'] || (isAr ? 'الوضع الليلي' : 'Dark Mode'))
      : (dict['الوضع النهاري'] || (isAr ? 'الوضع النهاري' : 'Light Mode'));
  });

  /* 8. page-specific deep translations */
  applyPageSpecific(lang, dict, pdict, isAr);
}

