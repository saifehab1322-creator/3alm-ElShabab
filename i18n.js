function setText(selector, text, isHtml) {
  const el = document.querySelector(selector);
  if (!el || text === undefined) return;
  if (isHtml) el.innerHTML = text;
  else el.textContent = text;
}

function setTextByAttr(selector, text) {
  const el = document.querySelector(selector);
  if (el && text !== undefined) el.textContent = text;
}

function setSelectOption(selector, index, text) {
  let sel;
  if (typeof selector === 'string') sel = document.querySelector(selector);
  else sel = selector;
  if (sel && sel.options && sel.options[index] && text !== undefined) {
    sel.options[index].text = text;
  }
}

function setNthFormLabel(n, text) {
  const labels = document.querySelectorAll('.form-body .form-group label, .form-body > label');
  if (labels[n] && text !== undefined) labels[n].textContent = text;
}

